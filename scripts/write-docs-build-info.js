// Pre-build step for `npm run docs`. Writes the current git commit SHA,
// branch, and an ISO timestamp into a tiny JS file the docs template
// includes. The footer then shows "Build YYYY-MM-DD · sha" so a viewer
// can verify they're looking at the same revision that's on production.
//
// Output: jsdoc-template/static/scripts/ll-build-info.js (gitignored)

"use strict";

const fs           = require("fs");
const path         = require("path");
const {execSync}   = require("child_process");

const REPO_URL = "https://github.com/LuckeyLogic/LibraryLoot";

function safeExec(cmd) {
  try {
    return execSync(cmd, {stdio: ["ignore", "pipe", "ignore"]})
      .toString()
      .trim();
  } catch (_) {
    return null;
  }
}

const sha       = safeExec("git rev-parse --short HEAD")       || "local";
const branch    = safeExec("git rev-parse --abbrev-ref HEAD")  || "local";
const buildDate = new Date().toISOString().slice(0, 19).replace("T", " ");

const info = {sha, branch, buildDate, repo: REPO_URL};

const outPath = path.join(
  __dirname,
  "..",
  "jsdoc-template",
  "static",
  "scripts",
  "ll-build-info.js"
);

const body =
  "/* Auto-generated by scripts/write-docs-build-info.js — do not edit. */\n" +
  "window.LL_BUILD = " + JSON.stringify(info, null, 2) + ";\n";

fs.writeFileSync(outPath, body);

console.log(
  `build info → ${path.relative(process.cwd(), outPath)}` +
  ` (sha=${info.sha} branch=${info.branch} date=${info.buildDate})`
);
